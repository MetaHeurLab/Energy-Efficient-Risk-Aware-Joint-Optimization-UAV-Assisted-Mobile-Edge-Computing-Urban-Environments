function timing=measure_application_runtime(baseCase,study,out)
% Isolated workstation timing; new seeds, full generations, no parallel pool.
out=char(java.io.File(out).getCanonicalPath());
if isfield(study,'SerialTimingOutput')
    expected=char(java.io.File(study.SerialTimingOutput).getCanonicalPath());
    assert(strcmpi(out,expected),'Application:TimingOutputBinding', ...
        'The output must match this study''s reserved serial timing directory.');
end
assert(~isfile(out),'Application:TimingOutputFile');
if isfolder(out)
    existing=dir(out);existing=existing(~ismember({existing.name},{'.','..'}));
    assert(isempty(existing),'Application:TimingExistingOutput', ...
        'Serial timing does not resume or overwrite existing output. Reserve a new empty directory.');
end
assert(isempty(gcp('nocreate')),'Application:TimingPool','Close the experiment pool before serial timing.');
maxNumCompThreads(1);
c=baseCase.Configuration;model=baseCase.Model;
assert(strcmp(c.CaseId,'baseline')&&c.population==40&&c.iterations==750,'Application:TimingBaseline');
methods=reshape(study.Methods,1,[]);M=numel(methods);R=5;
assert(M==12&&isequal(methods,reshape(c.methods,1,[])),'Application:TimingMethods');
originalSeedBase=c.runSeedBase;c.CaseId='serial_timing';c.runs=R;
c.runSeedBase=originalSeedBase+1000;c.workers=1;
for j=1:numel(study.Sources)
    source=study.Sources{j};
    if ~java.io.File(source).isAbsolute(),source=fullfile(application_root(),source);end
    assert(strcmp(sha256_file(source),study.SourceHashes{j}),'Application:TimingSource');
end
executionOrder=zeros(R,M);
for run=1:R,executionOrder(run,:)=mod((0:M-1)+run-1,M)+1;end
platform=struct('MATLABVersion',version,'MATLABRelease',version('-release'), ...
    'Architecture',computer('arch'),'OperatingSystem',getenv('OS'), ...
    'ProcessorIdentifier',getenv('PROCESSOR_IDENTIFIER'), ...
    'LogicalProcessors',java.lang.Runtime.getRuntime().availableProcessors(), ...
    'ComputationThreadsRequested',1,'ParallelPoolAbsent',true);
protocol=struct('Version','application_isolated_serial_timing_v1', ...
    'CaseId','serial_timing','StudyId',study.StudyId,'Configuration',c,'OutputDirectory',out, ...
    'Methods',{methods},'AlgorithmHashes',{study.AlgorithmHashes}, ...
    'TargetSourceSHA256',study.TargetSourceSHA256, ...
    'Sources',{study.Sources},'SourceHashes',{study.SourceHashes}, ...
    'ModelSHA256',text_hash(jsonencode(model)),'InputCaseId','baseline', ...
    'PopulationInput',c.population,'CompleteIterations',c.iterations,'RunsPerMethod',R, ...
    'Seeds',c.runSeedBase+(1:R),'NoEvaluationCap',true,'FreshRecipeCount',M*R, ...
    'ExecutionOrder',executionOrder,'OrderRule','Cyclic shift by one method per common seed; five shifts, not complete counterbalancing', ...
    'SearchRuntimeDefinition','application_job SearchRuntime_s; algorithm, objective observer and output capture; excludes post-search replay and save', ...
    'TaskRuntimeDefinition','application_job TotalTaskRuntime_s includes native/observer policy replays but excludes final job-file save', ...
    'NoHistoricalTimingImports',true,'ResumeAllowed',false,'WarmupIterations',3,'WarmupRunsPerMethod',1, ...
    'WarmupIncludedInSummary',false,'WarmupFullyRepresentsEveryBranch',false, ...
    'Platform',platform,'FiguresCreated',0, ...
    'OperatingTimescaleClaim','Workstation planning cost only; no onboard or edge-hardware deadline guarantee', ...
    'UnmeasuredCosts',{{'Communication','Prediction','Online scenario construction','Trajectory/resource execution','Onboard hardware scheduling'}});
token=text_hash(jsonencode(protocol));protocol.Token=token;
for folder={out,fullfile(out,'jobs'),fullfile(out,'warmup'),fullfile(out,'warmup','jobs')}
    if ~isfolder(folder{1}),mkdir(folder{1});end
end
save(fullfile(out,'protocol.mat'),'protocol','token','-v7');
write_json(fullfile(out,'protocol.json'),protocol);
save(fullfile(out,'fixed_instance.mat'),'c','model','-v7');

warmC=c;warmC.CaseId='serial_warmup';warmC.runs=1;warmC.iterations=3;
warmC.runSeedBase=originalSeedBase+2000;
warmProtocol=struct('Version','application_serial_warmup_v1','CaseId','serial_warmup', ...
    'StudyId',study.StudyId,'Configuration',warmC,'Methods',{methods}, ...
    'AlgorithmHashes',{study.AlgorithmHashes},'TargetSourceSHA256',study.TargetSourceSHA256, ...
    'Sources',{study.Sources},'SourceHashes',{study.SourceHashes}, ...
    'ModelSHA256',protocol.ModelSHA256,'ExcludedFromFormalStatistics',true, ...
    'ParentTimingToken',token,'NoEvaluationCap',true,'ResumeAllowed',false);
warmToken=text_hash(jsonencode(warmProtocol));warmProtocol.Token=warmToken;
warmOut=fullfile(out,'warmup');
write_json(fullfile(warmOut,'protocol.json'),warmProtocol);
warmRecords=cell(M,1);
for m=1:M
    warmRecords{m}=application_job(methods{m},1,warmC,model,warmOut,warmToken,study.AlgorithmHashes{m});
    assert(strcmp(warmRecords{m}.Termination,'complete_iterations'),'Application:TimingWarmup', ...
        'Warmup failed for %s: %s',methods{m},warmRecords{m}.ErrorMessage);
    assert(~warmRecords{m}.LoadedFromThisStudyCache,'Application:TimingWarmupFresh', ...
        'Serial warmup must also be fresh; use a new timing output directory.');
end
warmRecords=vertcat(warmRecords{:});
save(fullfile(warmOut,'warmup.mat'),'warmRecords','warmC','model','warmProtocol','warmToken','-v7');

runtimeMatrix=zeros(R,M);totalTaskRuntimeMatrix=zeros(R,M);recordCells=cell(M*R,1);
for run=1:R
    for orderIndex=1:M
        m=executionOrder(run,orderIndex);
        record=application_job(methods{m},run,c,model,out,token,study.AlgorithmHashes{m});
        assert(strcmp(record.Termination,'complete_iterations'),'Application:TimingRun', ...
            'Serial timing failed for %s run%d: %s',methods{m},run,record.ErrorMessage);
        assert(~record.LoadedFromThisStudyCache,'Application:TimingFresh', ...
            'Serial timing requires a fresh search; use another timing output directory.');
        runtimeMatrix(run,m)=record.SearchRuntime_s;
        totalTaskRuntimeMatrix(run,m)=record.TotalTaskRuntime_s;
        recordCells{(m-1)*R+run}=record;
        fprintf('SERIAL_TIMING %s run%d/%d search=%.6fs total_task=%.6fs\n', ...
            methods{m},run,R,record.SearchRuntime_s,record.TotalTaskRuntime_s);
    end
end
records=vertcat(recordCells{:});
assert(all(isfinite(runtimeMatrix(:)))&&all(runtimeMatrix(:)>0),'Application:TimingFinite');
assert(isempty(gcp('nocreate')),'Application:TimingPool');
summaryRows=cell(M,12);
for m=1:M
    q=records(strcmp({records.Method},methods{m}));
    warningRuns=sum(arrayfun(@(z)~isempty(z.LastWarningIdentifier)||~isempty(z.LastWarningMessage),q));
    summaryRows(m,:)={methods{m},R,mean(runtimeMatrix(:,m)),std(runtimeMatrix(:,m)), ...
        median(runtimeMatrix(:,m)),iqr(runtimeMatrix(:,m)),min(runtimeMatrix(:,m)),max(runtimeMatrix(:,m)), ...
        mean(totalTaskRuntimeMatrix(:,m)),median(totalTaskRuntimeMatrix(:,m)), ...
        mean([q.ModelEvaluationCalls]),warningRuns};
end
runtimeSummary=cell2table(summaryRows,'VariableNames',{'Method','Runs','MeanSearchSeconds', ...
    'StdSearchSeconds','MedianSearchSeconds','IQRSearchSeconds','MinSearchSeconds','MaxSearchSeconds', ...
    'MeanTotalTaskSeconds','MedianTotalTaskSeconds','MeanModelEvaluationCalls','WarningRuns'});
writetable(runtimeSummary,fullfile(out,'runtime_summary.csv'));
timing=struct('CaseId','serial_timing','StudyId',study.StudyId,'Methods',{methods}, ...
    'Seeds',c.runSeedBase+(1:R),'RunsPerMethod',R,'PopulationInput',c.population, ...
    'CompleteIterations',c.iterations,'ExecutionOrder',executionOrder, ...
    'RuntimeMatrix',runtimeMatrix,'TotalTaskRuntimeMatrix',totalTaskRuntimeMatrix, ...
    'RuntimeSummary',runtimeSummary,'Platform',platform,'Token',token, ...
    'TargetSourceSHA256',study.TargetSourceSHA256,'WarmupRecipes',M,'FormalRecipes',M*R, ...
    'OutputDirectory',out,'ResumeAllowed',false, ...
    'WarmupExcluded',true,'SearchRuntimeIncludesPostSearchChecks',false, ...
    'NoParallelWorkers',true,'Sources',{study.Sources},'SourceHashes',{study.SourceHashes}, ...
    'UnmeasuredCosts',{protocol.UnmeasuredCosts},'NoOnboardRealtimeClaim',true,'FiguresCreated',0);
save(fullfile(out,'serial_timing.mat'),'timing','runtimeMatrix','totalTaskRuntimeMatrix', ...
    'records','methods','c','model','protocol','token','runtimeSummary','-v7');
verify_records(records,c,model,protocol,out);
write_json(fullfile(out,'TIMING_SUMMARY.json'),struct('Status','complete','CaseId','serial_timing', ...
    'StudyId',study.StudyId,'Token',token,'Methods',{methods},'FormalRecipes',M*R, ...
    'WarmupRecipes',M,'WarmupExcluded',true,'RunsPerMethod',R, ...
    'PrimaryClock','SearchRuntime_s','PostSearchChecksExcludedFromPrimaryClock',true, ...
    'NoParallelWorkers',true,'Platform',platform,'NoOnboardRealtimeClaim',true, ...
    'UnmeasuredCosts',{protocol.UnmeasuredCosts},'FiguresCreated',0));
fprintf('SERIAL_TIMING_COMPLETE full_runs=%d warmups=%d figures=0\n',M*R,M);
end

function digest=text_hash(value)
engine=java.security.MessageDigest.getInstance('SHA-256');engine.update(unicode2native(value,'UTF-8'));
digest=lower(reshape(dec2hex(typecast(engine.digest(),'uint8'),2)',1,[]));
end
