function analysis=analyze_application_data(out)
% Analyze this case's native returned policies; no search or figure creation.
s=load(fullfile(out,'all_runs.mat'),'records','c','model','protocol','token');
r=s.records;c=s.c;protocol=s.protocol;token=s.token;
methods=reshape(c.methods,1,[]);R=c.runs;T=c.iterations;M=numel(methods);
assert(M==12&&R==30&&T==750&&numel(r)==M*R,'Application:AnalysisSize');
assert(isequal(methods,reshape(protocol.Methods,1,[]))&&strcmp(token,protocol.Token),'Application:AnalysisProtocol');
assert(all(strcmp({r.Termination},'complete_iterations')),'Application:IncompleteAnalysis');
target=find(strcmp(methods,'DFPQNO'));assert(isscalar(target),'Application:AnalysisTarget');
rngBefore=rng;
Y=zeros(R,M);IndependentY=zeros(R,M);ObserverY=zeros(R,M);
traces=zeros(R,T,M);rawCurves=zeros(R,T,M);
rows=cell(M,28);independentRows=cell(M,28);diagnosticRows=cell(M,10);
rawParts=cell(M,1);
for m=1:M
    q=r(strcmp({r.Method},methods{m}));[~,order]=sort([q.Run]);q=q(order);
    assert(isequal([q.Run],1:R)&&isequal([q.Seed],c.runSeedBase+(1:R)),'Application:AnalysisSeeds');
    assert(all([q.ActualIterations]==T)&&all([q.NativeCurveLength]==T),'Application:AnalysisIterations');
    validation=[q.Validation];independent=[q.IndependentValidation];training=[q.TrainingMetrics];
    observed=[q.ObserverValidation];Y(:,m)=[validation.Primary]';
    IndependentY(:,m)=[independent.Primary]';ObserverY(:,m)=[observed.Primary]';
    errorIds=cell(R,1);errorMessages=cell(R,1);warningIds=cell(R,1);warningMessages=cell(R,1);
    for k=1:R
        z=q(k);
        assert(strcmp(record_token(z),token),'Application:MixedAnalysis');
        assert(strcmp(z.AlgorithmSHA256,protocol.AlgorithmHashes{m}),'Application:AnalysisSource');
        assert(isequaln(z.BestPosition,z.RawReturnedPosition),'Application:NativePolicySelection');
        assert(isequaln(z.TrainingObjective,z.TrainingMetrics.Penalized),'Application:NativeTrainingObjective');
        assert(numel(z.RawReturnedCurve)==T&&numel(z.ObservedCurve)==T,'Application:AnalysisCurves');
        rawCurves(k,:,m)=reshape(z.RawReturnedCurve,1,[]);
        traces(k,:,m)=reshape(z.ObservedCurve,1,[]);
        errorIds{k}=record_text(z,{'ErrorIdentifier'});errorMessages{k}=record_text(z,{'ErrorMessage'});
        warningIds{k}=record_text(z,{'LastWarningIdentifier','WarningIdentifier'});
        warningMessages{k}=record_text(z,{'LastWarningMessage','WarningMessage'});
    end
    errors=sum(~cellfun(@isempty,errorIds)|~cellfun(@isempty,errorMessages));
    warnings=sum(~cellfun(@isempty,warningIds)|~cellfun(@isempty,warningMessages));
    rows(m,:)=summary_row(methods{m},validation,training,q,errors,warnings);
    independentRows(m,:)=summary_row(methods{m},independent,training,q,errors,warnings);
    differs=reshape(arrayfun(@(z)~isequaln(z.BestPosition,z.ObserverBestPosition),q),1,[]);
    mismatches=~[q.RawScoreExactlyReplays];
    diagnosticRows(m,:)={methods{m},R,mean(Y(:,m)),mean(ObserverY(:,m)), ...
        mean(Y(:,m)-ObserverY(:,m)),sum(differs),sum(mismatches), ...
        mean([q.TrainingObjective]-[q.ObserverTrainingObjective]), ...
        sum([validation.Feasible]),sum([observed.Feasible])};
    rawParts{m}=table(repmat(string(methods{m}),R,1),[q.Run]',[q.Seed]', ...
        [q.CandidateRows]',[q.ModelEvaluationCalls]',[q.ObjectiveCalls]', ...
        [q.PostSearchEvaluationCalls]',[q.InvalidCandidates]',[q.NonFiniteCandidates]', ...
        [q.NonFiniteObjectiveValues]',[q.TrainingObjective]',[validation.Primary]', ...
        [validation.Penalized]',[independent.Primary]',[independent.Penalized]', ...
        [observed.Primary]',[validation.Energy_kJ]',[validation.MeanLatency_s]', ...
        [validation.Latency95_s]',[validation.Completion]',[validation.Fairness]', ...
        [validation.CVaR]',[training.Feasible]',[validation.Feasible]', ...
        [independent.Feasible]',[validation.MinSafetyMargin_m]',[q.Runtime_s]', ...
        [q.ActualIterations]',[q.RawScoreExactlyReplays]',differs', ...
        string(errorIds),string(errorMessages),string(warningIds),string(warningMessages), ...
        string({q.Termination})','VariableNames',{'Method','Run','Seed','CandidateRows', ...
        'ModelEvaluationCalls','ObjectiveCalls','PostSearchEvaluationCalls','InvalidCandidates', ...
        'NonFiniteCandidates','NonFiniteObjectiveValues','TrainingObjective','Jval', ...
        'ValidationPenalized','IndependentJ','IndependentPenalized','ObserverJval','Energy_kJ', ...
        'MeanLatency_s','Latency95_s','Completion','Fairness','CVaR','TrainingFeasible', ...
        'ValidationFeasible','IndependentFeasible','MinimumSafetyMargin_m','ConcurrentRuntime_s', ...
        'NativeIterations','RawScoreExactlyReplays','NativePolicyDiffersFromObserver', ...
        'ErrorIdentifier','ErrorMessage','WarningIdentifier','WarningMessage','Termination'});
end
assert(all(isfinite(Y(:)))&&all(isfinite(IndependentY(:)))&&all(isfinite(ObserverY(:))),'Application:AnalysisFinite');
assert(all(isfinite(rawCurves(:)))&&all(isfinite(traces(:))),'Application:AnalysisFiniteCurves');
ranks=zeros(R,M);independentRanks=zeros(R,M);
for k=1:R
    ranks(k,:)=tiedrank(Y(k,:));independentRanks(k,:)=tiedrank(IndependentY(k,:));
end
names={'Method','Runs','MeanJ','StdJ','MedianJ','IQRJ','MinimumJ','MaximumJ', ...
    'MeanTrainingObjective','MeanValidationPenalized','TrainingFeasibleRuns','ValidationFeasibleRuns', ...
    'MinimumSafetyMargin_m','MeanEnergy_kJ','MeanLatency_s','Latency95_s','Completion','Fairness', ...
    'CVaR','MeanCandidateRows','MeanModelEvaluationCalls','MeanObjectiveCalls', ...
    'MeanPostSearchEvaluationCalls','ConcurrentMedianRuntime_s','InvalidCandidates', ...
    'NonFiniteCandidates','ErrorRuns','WarningRuns'};
summary=cell2table(rows,'VariableNames',names);summary.MeanSeedRank=mean(ranks,1)';
independentSummary=cell2table(independentRows,'VariableNames',names);
independentSummary.MeanSeedRank=mean(independentRanks,1)';
summary=sortrows(summary,'MeanJ');independentSummary=sortrows(independentSummary,'MeanJ');
observerDiagnostic=cell2table(diagnosticRows,'VariableNames',{'Method','Runs','NativeMeanJ', ...
    'ObserverMeanJ','MeanNativeMinusObserverJ','NativePolicyDiffersFromObserver', ...
    'NativeScoreMismatch','MeanNativeMinusObserverTrainingObjective', ...
    'NativeValidationFeasibleRuns','ObserverValidationFeasibleRuns'});
bootstrapSeed=24102012;bootstrapSamples=5000;
analysisStream=RandStream('mt19937ar','Seed',bootstrapSeed);
resample=randi(analysisStream,R,R,bootstrapSamples);
pairwise=paired_statistics(Y,methods,target,resample);
independentPairs=paired_statistics(IndependentY,methods,target,resample);
[friedmanP,~,friedmanStats]=friedman(Y,1,'off');
[independentFriedmanP,~,independentFriedmanStats]=friedman(IndependentY,1,'off');
raw=vertcat(rawParts{:});
writetable(raw,fullfile(out,'application_raw.csv'));
writetable(summary,fullfile(out,'performance_summary.csv'));
writetable(independentSummary,fullfile(out,'independent_validation_summary.csv'));
writetable(observerDiagnostic,fullfile(out,'native_observer_diagnostic.csv'));
writetable(pairwise,fullfile(out,'DFPQNO_paired_Wilcoxon_Holm.csv'));
writetable(independentPairs,fullfile(out,'DFPQNO_independent_Wilcoxon_Holm.csv'));
analysisSourceSHA256=sha256_file([mfilename('fullpath') '.m']);
save(fullfile(out,'analysis.mat'),'methods','c','Y','IndependentY','ObserverY','ranks', ...
    'independentRanks','traces','rawCurves','summary','independentSummary','observerDiagnostic', ...
    'pairwise','independentPairs','friedmanP','friedmanStats','independentFriedmanP', ...
    'independentFriedmanStats','protocol','token','analysisSourceSHA256','bootstrapSeed','bootstrapSamples','-v7');
assert(isequaln(rngBefore,rng),'Application:AnalysisRNG','Analysis changed the optimization RNG state.');
analysis=struct('CaseId',protocol.CaseId,'StudyId',protocol.StudyId,'Token',token, ...
    'TargetSourceSHA256',protocol.TargetSourceSHA256,'Methods',{methods}, ...
    'Runs',M*R,'RunsPerMethod',R,'PopulationInput',c.population,'CompleteIterations',T, ...
    'PrimaryPolicy','Native returned policy, evaluated after search; observer is diagnostic only', ...
    'DFPQNO_MeanJ',mean(Y(:,target)),'DFPQNO_SD',std(Y(:,target)), ...
    'DFPQNO_MeanOrdinal',1+sum(mean(Y,1)<mean(Y(:,target))), ...
    'DFPQNO_MeanSeedRank',mean(ranks(:,target)), ...
    'IndependentDFPQNO_MeanJ',mean(IndependentY(:,target)), ...
    'IndependentDFPQNO_MeanOrdinal',1+sum(mean(IndependentY,1)<mean(IndependentY(:,target))), ...
    'HolmFamily',M-1,'IndependentHolmFamily',M-1, ...
    'MultipleCasesJointMultiplicityControlled',false,'BootstrapSamples',bootstrapSamples, ...
    'BootstrapSeed',bootstrapSeed,'BootstrapIntervalsSimultaneous',false, ...
    'FriedmanP',friedmanP,'IndependentFriedmanP',independentFriedmanP, ...
    'Errors',sum(summary.ErrorRuns),'WarningRuns',sum(summary.WarningRuns), ...
    'InvalidCandidates',sum(summary.InvalidCandidates), ...
    'NativeObserverPolicyDifferences',sum(observerDiagnostic.NativePolicyDiffersFromObserver), ...
    'SourceAllRunsSHA256',sha256_file(fullfile(out,'all_runs.mat')), ...
    'AnalysisSourceSHA256',analysisSourceSHA256,'RNGUnchanged',true,'FiguresCreated',0);
write_json(fullfile(out,'ANALYSIS_SUMMARY.json'),analysis);
fprintf('APPLICATION_ANALYSIS case=%s native_rank=%d independent_rank=%d runs=%d figures=0\n', ...
    char(protocol.CaseId),analysis.DFPQNO_MeanOrdinal,analysis.IndependentDFPQNO_MeanOrdinal,M*R);
end

function row=summary_row(method,metrics,training,records,errors,warnings)
values=[metrics.Primary];
row={method,numel(records),mean(values),std(values),median(values),iqr(values), ...
    min(values),max(values),mean([records.TrainingObjective]),mean([metrics.Penalized]), ...
    sum([training.Feasible]),sum([metrics.Feasible]),min([metrics.MinSafetyMargin_m]), ...
    mean([metrics.Energy_kJ]),mean([metrics.MeanLatency_s]),mean([metrics.Latency95_s]), ...
    mean([metrics.Completion]),mean([metrics.Fairness]),mean([metrics.CVaR]), ...
    mean([records.CandidateRows]),mean([records.ModelEvaluationCalls]),mean([records.ObjectiveCalls]), ...
    mean([records.PostSearchEvaluationCalls]),median([records.Runtime_s]), ...
    sum([records.InvalidCandidates]),sum([records.NonFiniteCandidates]),errors,warnings};
end

function result=paired_statistics(values,methods,target,resample)
others=setdiff(1:numel(methods),target,'stable');rows=cell(numel(others),14);pvalues=ones(numel(others),1);
for j=1:numel(others)
    m=others(j);a=values(:,target);b=values(:,m);delta=b-a;
    tolerance=eps(a)+eps(b);active=abs(delta)>tolerance;
    if any(active)
        [pvalues(j),~,stats]=signrank(b,a,'method','approximate');signedRank=stats.signedrank;
        signedRanks=tiedrank(abs(delta(active)),0,0,tolerance(active));
        positive=sum(signedRanks(delta(active)>0));negative=sum(signedRanks(delta(active)<0));
        effect=(positive-negative)/sum(signedRanks);
    else
        signedRank=0;effect=0;pvalues(j)=1;
    end
    sampledDelta=mean(delta(resample),1);sampledComparator=mean(b(resample),1);
    ci=prctile(sampledDelta,[2.5 97.5]);percentCI=prctile(100*sampledDelta./sampledComparator,[2.5 97.5]);
    rows(j,:)={methods{m},sum(delta>0),sum(delta==0),sum(delta<0),mean(delta), ...
        100*mean(delta)/mean(b),ci(1),ci(2),percentCI(1),percentCI(2),effect,signedRank,pvalues(j),NaN};
end
[sorted,order]=sort(pvalues);adjusted=min(1,cummax((numel(sorted)-(1:numel(sorted))'+1).*sorted));
corrected=zeros(size(pvalues));corrected(order)=adjusted;
for j=1:size(rows,1),rows{j,end}=corrected(j);end
result=cell2table(rows,'VariableNames',{'Comparator','DFPWins','Ties','DFPLosses', ...
    'MeanAbsoluteReduction','MeanPercentReduction','PairedCI95Low','PairedCI95High', ...
    'PercentCI95Low','PercentCI95High','RankBiserialFavorsDFP','SignedRank','RawP','HolmP'});
end

function token=record_token(record)
if isfield(record,'FreshStudyToken')
    token=record.FreshStudyToken;
elseif isfield(record,'StudyToken')
    token=record.StudyToken;
else
    token=record.Token;
end
end

function value=record_text(record,names)
value='';
for k=1:numel(names)
    if isfield(record,names{k}),value=char(record.(names{k}));return,end
end
end
