function provenance=export_application_data(out)
% Save complete inputs for later plotting; never create figures or rerun search.
inputNames={'all_runs.mat','analysis.mat','fixed_instance.mat'};
inputFiles=cellfun(@(name)fullfile(out,name),inputNames,'UniformOutput',false);
assert(all(cellfun(@isfile,inputFiles)),'Application:ExportInputs');
s=load(inputFiles{1},'records','c','model','protocol','token');
a=load(inputFiles{2},'methods','c','Y','IndependentY','ObserverY','traces','rawCurves','token');
f=load(inputFiles{3},'c','model');
assert(isequaln(s.c,f.c)&&isequaln(s.c,a.c)&&isequaln(s.model,f.model),'Application:ExportModel');
assert(strcmp(s.token,s.protocol.Token)&&strcmp(s.token,a.token),'Application:ExportToken');
assert(all(strcmp({s.records.Termination},'complete_iterations')),'Application:ExportIncomplete');
methods=reshape(s.c.methods,1,[]);R=s.c.runs;T=s.c.iterations;M=numel(methods);D=s.c.dimension;
assert(M==12&&R==30&&T==750&&numel(s.records)==M*R&&isequal(methods,a.methods),'Application:ExportProtocol');
seeds=s.c.runSeedBase+(1:R);rngBefore=rng;
native=struct('Curves',zeros(R,T,M),'Positions',zeros(R,D,M), ...
    'ReturnedScore',zeros(R,M),'TrainingObjective',zeros(R,M), ...
    'TrainingMetrics',repmat(s.records(1).TrainingMetrics,R,M), ...
    'ValidationMetrics',repmat(s.records(1).Validation,R,M), ...
    'IndependentValidationMetrics',repmat(s.records(1).IndependentValidation,R,M));
observer=struct('Curves',zeros(R,T,M),'Positions',zeros(R,D,M), ...
    'TrainingObjective',zeros(R,M), ...
    'TrainingMetrics',repmat(s.records(1).ObserverTrainingMetrics,R,M), ...
    'ValidationMetrics',repmat(s.records(1).ObserverValidation,R,M));
hasObserverIndependent=isfield(s.records,'ObserverIndependentValidation');
if hasObserverIndependent
    observer.IndependentValidationMetrics=repmat(s.records(1).ObserverIndependentValidation,R,M);
end
metricNames={'Primary','Penalized','Penalty','Energy_kJ','MeanLatency_s','Latency95_s', ...
    'Completion','Fairness','CVaR','Feasible','MaxViolation','MinSafetyMargin_m', ...
    'FlightEnergy_J','WorstBattery_J','MaxSpeed_m_s','MaxAcceleration_m_s2'};
groups={'NativeTraining','NativeValidation','NativeIndependentValidation','ObserverTraining','ObserverValidation'};
numericNames={'Run','Seed','NativeReturnedScore','NativeTrainingObjective', ...
    'ObserverTrainingObjective','RawScoreExactlyReplays','NativePolicyDiffersFromObserver', ...
    'CandidateRows','ModelEvaluationCalls','PostSearchEvaluationCalls','Runtime_s'};
groupNames=cell(1,numel(groups));
for group=1:numel(groups),groupNames{group}=strcat(groups{group},'_',metricNames);end
numericNames=[numericNames,groupNames{:}];
policyValues=zeros(M*R,numel(numericNames));policyMethods=strings(M*R,1);policySourceSHA=strings(M*R,1);
representatives=cell(M,1);convergenceParts=cell(M,1);ordinal=max(1,ceil([.25 .75]*R));
for m=1:M
    records=s.records(strcmp({s.records.Method},methods{m}));[~,order]=sort([records.Run]);records=records(order);
    assert(isequal([records.Run],1:R)&&isequal([records.Seed],seeds),'Application:ExportSeeds');
    for k=1:R
        z=records(k);row=(m-1)*R+k;
        assert(strcmp(z.AlgorithmSHA256,s.protocol.AlgorithmHashes{m}),'Application:ExportSource');
        assert(isequaln(z.BestPosition,z.RawReturnedPosition),'Application:ExportNative');
        assert(numel(z.RawReturnedCurve)==T&&numel(z.ObservedCurve)==T&& ...
            numel(z.BestPosition)==D&&numel(z.ObserverBestPosition)==D,'Application:ExportShape');
        assert(isequaln(z.Validation.Primary,a.Y(k,m))&& ...
            isequaln(z.IndependentValidation.Primary,a.IndependentY(k,m))&& ...
            isequaln(z.ObserverValidation.Primary,a.ObserverY(k,m)),'Application:ExportMetrics');
        native.Curves(k,:,m)=reshape(z.RawReturnedCurve,1,[]);
        native.Positions(k,:,m)=reshape(z.BestPosition,1,[]);
        native.ReturnedScore(k,m)=z.RawReturnedScore;native.TrainingObjective(k,m)=z.TrainingObjective;
        native.TrainingMetrics(k,m)=z.TrainingMetrics;native.ValidationMetrics(k,m)=z.Validation;
        native.IndependentValidationMetrics(k,m)=z.IndependentValidation;
        observer.Curves(k,:,m)=reshape(z.ObservedCurve,1,[]);
        observer.Positions(k,:,m)=reshape(z.ObserverBestPosition,1,[]);
        observer.TrainingObjective(k,m)=z.ObserverTrainingObjective;
        observer.TrainingMetrics(k,m)=z.ObserverTrainingMetrics;observer.ValidationMetrics(k,m)=z.ObserverValidation;
        if hasObserverIndependent,observer.IndependentValidationMetrics(k,m)=z.ObserverIndependentValidation;end
        policyMethods(row)=methods{m};policySourceSHA(row)=z.AlgorithmSHA256;
        policyValues(row,1:11)=[k,z.Seed,z.RawReturnedScore,z.TrainingObjective, ...
            z.ObserverTrainingObjective,z.RawScoreExactlyReplays,~isequaln(z.BestPosition,z.ObserverBestPosition), ...
            z.CandidateRows,z.ModelEvaluationCalls,z.PostSearchEvaluationCalls,z.Runtime_s];
        metrics={z.TrainingMetrics,z.Validation,z.IndependentValidation,z.ObserverTrainingMetrics,z.ObserverValidation};
        for group=1:numel(groups)
            indices=11+(group-1)*numel(metricNames)+(1:numel(metricNames));
            policyValues(row,indices)=cellfun(@(name)double(metrics{group}.(name)),metricNames);
        end
    end
    ranked=sortrows([a.Y(:,m),(1:R)'],[1 2]);selected=ranked(ceil(R/2),2);z=records(selected);
    [validationScore,validationMetric,detail]=evaluate_policy(z.BestPosition,s.c,s.model,s.model.validation);
    assert(isequaln(validationMetric,z.Validation)&&isequaln(validationScore,z.Validation.Penalized), ...
        'Application:RepresentativeReplay','Native representative %s run%d does not replay.',methods{m},selected);
    representatives{m}=struct('Method',methods{m},'Run',selected,'Seed',z.Seed, ...
        'ValidationOrder',ceil(R/2),'TrainingObjective',z.TrainingObjective, ...
        'ValidationObjective',validationScore,'ValidationMetric',validationMetric, ...
        'IndependentValidationMetric',z.IndependentValidation,'Position',z.BestPosition, ...
        'Policy',detail.policy,'ValidationDetail',detail);
    returned=native.Curves(:,:,m);observed=observer.Curves(:,:,m);
    sortedReturned=sort(returned,1);sortedObserved=sort(observed,1);
    values=[(1:T)',repmat(R,T,1),mean(returned,1)',median(returned,1)',std(returned,0,1)', ...
        sortedReturned(ordinal(1),:)',sortedReturned(ordinal(2),:)', ...
        mean(observed,1)',median(observed,1)',std(observed,0,1)', ...
        sortedObserved(ordinal(1),:)',sortedObserved(ordinal(2),:)'];
    convergenceParts{m}=[table(repmat(string(methods{m}),T,1),'VariableNames',{'Method'}), ...
        array2table(values,'VariableNames',{'Iteration','Runs','NativeMean','NativeMedian','NativeStd', ...
        'NativeP25NearestRank','NativeP75NearestRank','ObserverMean','ObserverMedian','ObserverStd', ...
        'ObserverP25NearestRank','ObserverP75NearestRank'})];
end
assert(isequaln(native.Curves,a.rawCurves)&&isequaln(observer.Curves,a.traces),'Application:ExportCurves');
assert(isequaln(rngBefore,rng),'Application:ExportRNG','Export changed the optimization RNG state.');
schema=struct('Version','native_policy_application_data_v2', ...
    'CurveDimensions','run x iteration x method','PositionDimensions','run x dimension x method', ...
    'MetricDimensions','run x method','MethodsOrder','protocol.Methods', ...
    'RunIds',1:R,'SeedOrder','configuration.runSeedBase + run index', ...
    'PrimaryPolicy','Unchanged native returned position; observer minimum is diagnostic only', ...
    'CurveValues','Native and observer raw penalized training objectives, retained separately', ...
    'Quartiles','Nearest-rank empirical order statistics at ceil(0.25*R), ceil(0.75*R)', ...
    'RepresentativeRule','Ascending native Validation.Primary, then Run; actual lower median run ceil(R/2)', ...
    'RepresentativeUsesIndependentValidation',false,'RepresentativeIsBest',false, ...
    'ObserverIndependentMetricsAvailable',hasObserverIndependent, ...
    'NoSearchPerformed',true,'NoFiguresCreated',true);
plotData=struct('Schema',schema,'Methods',{methods},'Seeds',seeds,'Iterations',1:T, ...
    'CaseId',s.protocol.CaseId,'StudyId',s.protocol.StudyId, ...
    'TargetSourceSHA256',s.protocol.TargetSourceSHA256,'StudyToken',s.token, ...
    'Native',native,'Observer',observer,'Representatives',{representatives}, ...
    'Configuration',s.c,'Model',s.model,'Protocol',s.protocol, ...
    'InputFiles',{inputNames},'InputSHA256',{cellfun(@sha256_file,inputFiles,'UniformOutput',false)}, ...
    'ExporterSHA256',sha256_file([mfilename('fullpath') '.m']), ...
    'RepresentativeValidationReplayCalls',M,'RNGUnchanged',true);
save(fullfile(out,'plot_data.mat'),'plotData','-v7');
convergence=vertcat(convergenceParts{:});writetable(convergence,fullfile(out,'convergence.csv'));
policySummary=[table(policyMethods,policySourceSHA,'VariableNames',{'Method','AlgorithmSHA256'}), ...
    array2table(policyValues,'VariableNames',numericNames)];
writetable(policySummary,fullfile(out,'policy_summary.csv'));
outputNames={'plot_data.mat','convergence.csv','policy_summary.csv'};
outputFiles=cellfun(@(name)fullfile(out,name),outputNames,'UniformOutput',false);
provenance=struct('Schema',schema,'CaseId',s.protocol.CaseId,'StudyId',s.protocol.StudyId, ...
    'StudyToken',s.token,'TargetSourceSHA256',s.protocol.TargetSourceSHA256, ...
    'InputFiles',{inputNames},'InputSHA256',{plotData.InputSHA256}, ...
    'ExporterFile','src/export_application_data.m','ExporterSHA256',plotData.ExporterSHA256, ...
    'OutputFiles',{outputNames},'OutputSHA256',{cellfun(@sha256_file,outputFiles,'UniformOutput',false)}, ...
    'Policies',M*R,'IndividualNativeHistories',M*R,'IndividualObserverHistories',M*R, ...
    'ConvergenceSummaryRows',height(convergence),'PolicySummaryRows',height(policySummary), ...
    'RepresentativeValidationReplayCalls',M,'RepresentativeReplaysExact',true, ...
    'ReplayCallsExcludedFromSearch',true,'IndependentPolicySelectionChanged',false, ...
    'RNGUnchanged',isequaln(rngBefore,rng),'OptimizationRunsStarted',0,'FiguresCreated',0);
assert(provenance.RNGUnchanged,'Application:ExportRNG');
write_json(fullfile(out,'EXPORT_PROVENANCE.json'),provenance);
fprintf('APPLICATION_DATA_EXPORTED case=%s policies=%d histories=%d+%d figures=0\n', ...
    char(s.protocol.CaseId),M*R,M*R,M*R);
end
