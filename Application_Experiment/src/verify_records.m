function report=verify_records(records,c,model,protocol,out)
% Recompute native-policy metrics and audit actual generation witnesses.
assert(isfield(protocol,'Token')&& ...
    strcmp(protocol.Token,text_hash(jsonencode(rmfield(protocol,'Token')))), ...
    'ApplicationAudit:ProtocolToken');
assert(numel(c.methods)==12&&numel(records)==numel(c.methods)*c.runs&& ...
    c.population==40&&c.dimension==524,'ApplicationAudit:StudySize');
assert(numel(model.training)==12&&numel(model.validation)==100&& ...
    numel(model.independentValidation)==100,'ApplicationAudit:ScenarioSets');
assert(isempty(intersect(model.training,model.validation))&& ...
    isempty(intersect(model.training,model.independentValidation))&& ...
    isempty(intersect(model.validation,model.independentValidation)), ...
    'ApplicationAudit:ScenarioOverlap');
if isfield(protocol,'Methods')
    assert(isequal(reshape(protocol.Methods,1,[]),reshape(c.methods,1,[])), ...
        'ApplicationAudit:Methods');
end
if isfield(protocol,'Configuration')
    assert(isequaln(c,protocol.Configuration),'ApplicationAudit:Configuration');
end
if isfield(protocol,'ModelSHA256')
    assert(strcmp(text_hash(jsonencode(model)),protocol.ModelSHA256), ...
        'ApplicationAudit:ModelHash');
end
assert(isfield(protocol,'Sources')&&isfield(protocol,'SourceHashes')&& ...
    numel(protocol.Sources)==numel(protocol.SourceHashes),'ApplicationAudit:Sources');
root=application_root();
for j=1:numel(protocol.Sources)
    file=protocol.Sources{j};
    if ~java.io.File(file).isAbsolute(),file=fullfile(root,file);end
    assert(strcmp(sha256_file(file),protocol.SourceHashes{j}), ...
        'ApplicationAudit:ChangedSource','Frozen source changed: %s',file);
end
beforeRNG=rng;policyReplayCalls=0;observerReplayCalls=0;
candidateCounts=zeros(numel(records),1);modelCounts=candidateCounts;
invalidCounts=candidateCounts;nonfiniteCounts=candidateCounts;objectiveNonfiniteCounts=candidateCounts;
policyDifferences=0;warningRuns=0;exactBoundsExceptions=0;checked=0;
for m=1:numel(c.methods)
    method=c.methods{m};q=records(strcmp({records.Method},method));
    [~,order]=sort([q.Run]);q=q(order);
    assert(numel(q)==c.runs&&isequal([q.Run],1:c.runs)&& ...
        isequal([q.Seed],c.runSeedBase+(1:c.runs)),'ApplicationAudit:RunSeeds');
    executedSource=which(method);
    assert(~isempty(executedSource),'ApplicationAudit:MissingAlgorithm');
    sourceHash=sha256_file(executedSource);
    if isfield(protocol,'AlgorithmHashes')
        assert(strcmp(sourceHash,protocol.AlgorithmHashes{m}),'ApplicationAudit:AlgorithmSource');
    end
    for k=1:numel(q)
        z=q(k);ip=z.IterationProof;checked=checked+1;
        assert(strcmp(z.FreshStudyToken,protocol.Token)&&strcmp(z.AlgorithmSHA256,sourceHash), ...
            'ApplicationAudit:RecordSource');
        assert(z.SearchCompleted&&z.VerificationPassed&& ...
            strcmp(z.Termination,'complete_iterations')&&isempty(z.ErrorStage)&& ...
            isempty(z.ErrorIdentifier)&&isempty(z.ErrorMessage),'ApplicationAudit:FailedRecord');
        assert(z.Population==c.population&&z.RequestedIterations==c.iterations&& ...
            z.ActualIterations==c.iterations&&z.NativeCurveLength==c.iterations);
        assert(ip.Count==c.iterations&&isequal(ip.Indices,1:c.iterations)&& ...
            isequal(size(ip.Population),[1,c.iterations])&& ...
            all(isfinite(ip.Population))&&all(ip.Population==fix(ip.Population)));
        assert(isnumeric(z.RawReturnedCurve)&&isreal(z.RawReturnedCurve)&& ...
            isequal(size(z.RawReturnedCurve),[1,c.iterations])&& ...
            all(isfinite(z.RawReturnedCurve))&&all(diff(z.RawReturnedCurve)<=0)&& ...
            isequaln(z.RawReturnedCurve,ip.NativeBest)&& ...
            isequaln(z.RawReturnedCurve(end),z.RawReturnedScore));
        assert(isequal(size(z.ObservedCurve),[1,c.iterations])&& ...
            all(isfinite(z.ObservedCurve))&&all(diff(z.ObservedCurve)<=0)&& ...
            isequaln(z.ObservedCurve,ip.ObserverBest)&& ...
            isequaln(z.ObservedCurve(end),z.ObserverTrainingObjective));
        assert(z.NoEvaluationCap&&~z.ValidationDuringSearch&& ...
            ~z.IndependentValidationDuringSearch&&~z.ObserverConsumesRandomNumbers);
        counts=[z.CandidateRows,z.ModelEvaluationCalls,z.ObjectiveCalls, ...
            z.InvalidCandidates,z.NonFiniteCandidates,z.NonFiniteObjectiveValues];
        assert(all(isfinite(counts))&&all(counts>=0)&&all(counts==fix(counts)));
        assert(z.Evaluations==z.CandidateRows&& ...
            z.ObjectiveCalls==numel(z.ObjectiveBatchRows)&& ...
            all(z.ObjectiveBatchRows>=0&z.ObjectiveBatchRows==fix(z.ObjectiveBatchRows))&& ...
            sum(z.ObjectiveBatchRows)==z.CandidateRows&& ...
            z.ModelEvaluationCalls==z.CandidateRows-z.InvalidCandidates&& ...
            z.NonFiniteCandidates<=z.InvalidCandidates&& ...
            z.NonFiniteObjectiveValues<=z.ModelEvaluationCalls,'ApplicationAudit:CandidateCounts');
        if strcmp(method,'DFPQNO')
            assert(z.TargetStandaloneCore&&z.TargetIterationsWitnessedByObjectiveBatches&& ...
                isequal(z.ObjectiveBatchRows,[2*c.population,repmat(c.population,1,c.iterations)])&& ...
                z.CandidateRows==c.population*(c.iterations+2));
        end
        if strcmp(method,'mLSHADE_SPACMA')
            assert(ip.Population(1)==c.population&& ...
                all(ip.Population>=4&ip.Population<=c.population)&& ...
                all(diff(ip.Population)<=0)&& ...
                z.CandidateRows==c.population+sum(ip.Population));
        else
            assert(all(ip.Population==c.population));
            expected=expected_candidates(method,c.population,c.iterations);
            if isfinite(expected)
                assert(z.CandidateRows==expected,'ApplicationAudit:NativeEvaluationCount');
            end
        end
        assert(isequal(z.TrainingScenarioIndices,model.training)&& ...
            isequal(z.ValidationScenarioIndices,model.validation)&& ...
            isequal(z.IndependentValidationScenarioIndices,model.independentValidation));
        assert(isequaln(z.BestPosition,z.RawReturnedPosition)&& ...
            isequal(size(z.BestPosition),[1,c.dimension])&&isreal(z.BestPosition)&& ...
            all(isfinite(z.BestPosition))&& ...
            all(z.BestPosition>=-z.BoundsTolerance&z.BestPosition<=1+z.BoundsTolerance));
        exactBounds=all(z.BestPosition>=0&z.BestPosition<=1);
        assert(z.RawPositionShapeValid&&z.RawPositionInBounds&& ...
            z.RawPositionWithinExactBounds==exactBounds);
        exactBoundsExceptions=exactBoundsExceptions+double(~exactBounds);
        [trainingValue,trainingMetric]=evaluate_policy(z.BestPosition,c,model,model.training);
        [~,validationMetric]=evaluate_policy(z.BestPosition,c,model,model.validation);
        [~,independentMetric]=evaluate_policy(z.BestPosition,c,model,model.independentValidation);
        policyReplayCalls=policyReplayCalls+3;
        assert(isequaln(trainingValue,z.TrainingObjective)&& ...
            isequaln(trainingMetric,z.TrainingMetrics)&& ...
            isequaln(validationMetric,z.Validation)&& ...
            isequaln(independentMetric,z.IndependentValidation),'ApplicationAudit:NativePolicyReplay');
        assert(z.RawScoreExactlyReplays&&isequaln(z.RawReturnedScore,trainingValue)&& ...
            isequaln(z.RawPositionTrainingObjective,trainingValue)&& ...
            isequaln(z.RawPositionTrainingMetrics,trainingMetric)&& ...
            isequaln(z.RawScoreMinusRecomputed,z.RawReturnedScore-trainingValue), ...
            'ApplicationAudit:NativeScore');
        differs=~isequaln(z.BestPosition,z.ObserverBestPosition);
        assert(z.RawPositionEqualsObserverBest==~differs);
        if differs
            [observedValue,observedMetric]=evaluate_policy(z.ObserverBestPosition,c,model,model.training);
            [~,observedValidation]=evaluate_policy(z.ObserverBestPosition,c,model,model.validation);
            observerReplayCalls=observerReplayCalls+2;
        else
            observedValue=trainingValue;observedMetric=trainingMetric;
            observedValidation=validationMetric;
        end
        assert(isequaln(observedValue,z.ObserverTrainingObjective)&& ...
            isequaln(observedMetric,z.ObserverTrainingMetrics)&& ...
            isequaln(observedValidation,z.ObserverValidation),'ApplicationAudit:ObserverReplay');
        assert(z.PostSearchEvaluationCalls==3+2*double(differs)&& ...
            z.NativePolicyReplayCalls==3&&z.RawPositionVerificationCalls==1&& ...
            z.ObserverPolicyReplayCalls==2*double(differs));
        assert(isstruct(z.InitialRNGState)&&isequaln(z.FinalSearchRNGState,z.PostSearchRNGState));
        assert(isfinite(z.SearchRuntime_s)&&z.SearchRuntime_s>=0&& ...
            z.Runtime_s==z.SearchRuntime_s&&z.TotalTaskRuntime_s>=z.SearchRuntime_s&& ...
            ~z.RuntimeIncludesPostSearchChecks);
        assert(ischar(z.AlgorithmTranscript)&&ischar(z.LastWarningMessage)&& ...
            ischar(z.LastWarningIdentifier),'ApplicationAudit:DiagnosticTypes');
        warningRuns=warningRuns+double(~isempty(z.LastWarningMessage));
        policyDifferences=policyDifferences+double(differs);
        candidateCounts(checked)=z.CandidateRows;modelCounts(checked)=z.ModelEvaluationCalls;
        invalidCounts(checked)=z.InvalidCandidates;nonfiniteCounts(checked)=z.NonFiniteCandidates;
        objectiveNonfiniteCounts(checked)=z.NonFiniteObjectiveValues;
    end
end
assert(isequaln(beforeRNG,rng),'ApplicationAudit:ReplayRNG');
report=struct('Token',protocol.Token,'Records',checked,'Methods',{c.methods}, ...
    'PopulationInput',c.population,'CompleteIterations',c.iterations,'RunsPerMethod',c.runs, ...
    'ScenarioCounts',[numel(model.training),numel(model.validation),numel(model.independentValidation)], ...
    'AllNativePoliciesExactlyReplayed',true,'AllNativeReturnedScoresExactlyReplayed',true, ...
    'AllGenerationWitnessesVerified',true,'NoFEStoppingRule',true,'NoHistoryRepairOrPadding',true, ...
    'NoHistoricalStudyImports',true,'NativePolicyIsPrimary',true,'ValidationDuringSearch',false, ...
    'IndependentValidationDuringSearch',false,'RawReturnedScoreMismatchCount',0, ...
    'ObserverPolicyDiffersCount',policyDifferences,'ReturnedPolicyOutsideExactBoundsCount',exactBoundsExceptions, ...
    'TotalCandidateRows',sum(candidateCounts),'TotalSearchModelCalls',sum(modelCounts), ...
    'TotalInvalidCandidates',sum(invalidCounts),'TotalNonfiniteCandidates',sum(nonfiniteCounts), ...
    'TotalNonfiniteObjectiveValues',sum(objectiveNonfiniteCounts),'RunsWithLastWarning',warningRuns, ...
    'NativePolicyReplayCalls',policyReplayCalls,'ObserverPolicyReplayCalls',observerReplayCalls, ...
    'VerificationCallsExcludedFromSearchCounts',true,'SearchRandomStreamUnchangedByReplay',true, ...
    'SourcesVerified',numel(protocol.Sources),'VerifierSHA256',sha256_file([mfilename('fullpath') '.m']), ...
    'OptimizationRunsStarted',0,'Passed',true);
write_json(fullfile(out,'VERIFY.json'),report);
end

function count=expected_candidates(method,N,T)
switch method
    case {'BBO','IVYA','SSLO','NRBO'},count=N+N*T;
    case {'BKA','AROA'},count=N+2*N*T;
    case 'TOC',count=N+(N-1)*T;
    case 'NDO',count=N+3*N*T;
    case 'GJA',count=N+N*T+floor(T/5)*ceil(0.1*N);
    otherwise,count=NaN;
end
end

function digest=text_hash(value)
engine=java.security.MessageDigest.getInstance('SHA-256');
engine.update(unicode2native(value,'UTF-8'));
digest=lower(reshape(dec2hex(typecast(engine.digest(),'uint8'),2)',1,[]));
end
